// Read-only verification; never connects to or changes the production database.
const fs = require('node:fs');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const root = path.resolve(__dirname,'..');
// Fail on broken entry-point URLs before running slower unit/database tests.
require('./update-assets.cjs').validateAssets(fs.readFileSync(path.join(root,'index.html'),'utf8'));
function run(args) {
  const result = spawnSync(process.execPath,args,{cwd:root,stdio:'inherit'});
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status || 1);
}
for (const file of fs.readdirSync(path.join(root,'js')).filter(file=>file.endsWith('.js'))) run(['--check',`js/${file}`]);
for (const file of fs.readdirSync(path.join(root,'scripts')).filter(file=>file.endsWith('.cjs'))) run(['--check',`scripts/${file}`]);
if (fs.existsSync(path.join(root,'auth'))) {
  for (const file of fs.readdirSync(path.join(root,'auth')).filter(file=>file.endsWith('.mjs'))) run(['--check',`auth/${file}`]);
}
const {buildSync} = require('esbuild');
const editorBuild = buildSync({absWorkingDir:root,entryPoints:['editor/study-editor.js'],bundle:true,format:'iife',target:['es2020'],supported:{'template-literal':false},minify:true,legalComments:'eof',write:false,
  banner:{js:'/* Generated by scripts/build-study-editor.cjs; edit editor/study-editor.js. Licenses: editor/THIRD-PARTY-NOTICES.txt */'}});
const expectedEditor = editorBuild.outputFiles[0].text.replace(/\r\n/g,'\n');
const actualEditor = fs.readFileSync(path.join(root,'js/study-editor.js'),'utf8').replace(/\r\n/g,'\n');
if (actualEditor !== expectedEditor) throw new Error('Study editor bundle is stale. Run: node scripts/build-study-editor.cjs');
const tests = fs.readdirSync(path.join(root,'tests')).filter(file=>file.endsWith('.cjs')).sort();
for (const file of tests) run([`tests/${file}`]);
run(['scripts/test-auth-db.cjs']);
require('./update-assets.cjs').updateAssets(true);
console.log(`PASS: JavaScript syntax, ${tests.length} regression suites, isolated PostgreSQL tests, static asset versions`);
