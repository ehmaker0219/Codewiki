// Committed browser bundle keeps GitHub Pages and local previews build-free.
const {buildSync}=require('esbuild');
const path=require('node:path');
const fs=require('node:fs');
const root=path.resolve(__dirname,'..');
const result=buildSync({absWorkingDir:root,entryPoints:['editor/study-editor.js'],metafile:true,
  // Escape multiline strings so meaningful Markdown spaces are not emitted at EOL.
  bundle:true,format:'iife',target:['es2020'],supported:{'template-literal':false},minify:true,legalComments:'eof',
  outfile:'js/study-editor.js',banner:{js:'/* Generated by scripts/build-study-editor.cjs; edit editor/study-editor.js. Licenses: editor/THIRD-PARTY-NOTICES.txt */'}});
const notices=new Map();
for(const input of Object.keys(result.metafile.inputs).filter(file=>file.includes('node_modules/'))){
  let dir=path.dirname(path.resolve(root,input));
  let pkg;
  while(dir!==path.dirname(dir)){
    const manifest=path.join(dir,'package.json');
    if(fs.existsSync(manifest)){pkg=JSON.parse(fs.readFileSync(manifest,'utf8'));if(pkg.name)break;}
    dir=path.dirname(dir);
  }
  const key=`${pkg.name}@${pkg.version}`;
  if(notices.has(key))continue;
  const license=fs.readdirSync(dir).find(file=>/^licen[sc]e(?:-mit)?(?:\.(?:txt|md))?$/i.test(file));
  if(!license)throw new Error(`Missing license for ${key}`);
  notices.set(key,`${key}\n${fs.readFileSync(path.join(dir,license),'utf8').trim()}\n`);
}
fs.writeFileSync(path.join(root,'editor/THIRD-PARTY-NOTICES.txt'),[...notices].sort(([a],[b])=>a.localeCompare(b)).map(([,notice])=>notice).join('\n--------------------\n\n'));
console.log('Built local rich-text editor.');
