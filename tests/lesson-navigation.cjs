const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ctx=vm.createContext({window:{},currentDocId:'abap-basics',isDocumentPending:()=>false,currentTrack:'abap'});
for(const file of ['data','ui5-data','class-notes','lesson-days']) vm.runInContext(fs.readFileSync(`js/${file}.js`,'utf8'),ctx);
const src=fs.readFileSync('js/app.js','utf8');
vm.runInContext(src.slice(src.indexOf('  function renderDateNavigation'),src.indexOf('  // 좌측 고정 사이드바 렌더링')),ctx);
const docs=Object.values(ctx.window.WIKI_DOCS).filter(d=>d.track==='abap');
const html=ctx.renderDateNavigation(docs,new Set());
for(const day of ['11','12','13','16','17','18','19']) assert.ok(html.includes('2026-11-'+day));
assert.equal((html.match(/href=/g)||[]).length,7);
assert.ok(!html.includes('abap-basics'));
assert.ok(ctx.window.WIKI_DOCS['lesson-2026-11-11'].sections.length > 0);
assert.ok(!html.includes('날짜 미지정'));
assert.ok(!html.includes('href="#doc/welcome-abap"'));
assert.ok(html.indexOf('1주차') !== -1 && html.indexOf('1주차') < html.indexOf('2026-11-11'));
assert.ok(html.indexOf('2026-11-13') < html.indexOf('2주차') && html.indexOf('2주차') < html.indexOf('2026-11-16'));
assert.equal((html.match(/nav-week-divider/g)||[]).length,2);
assert.ok(html.includes('<span aria-hidden="true">1주차</span>'));
assert.ok(!html.includes('<details'));
ctx.window.WIKI_LESSON_DAYS.unshift({date:'2026-10-19',title:'2026-10-19 (월)',docId:'lesson-2026-10-19',track:'abap',week:-2});
const preWeekHtml=ctx.renderDateNavigation(docs,new Set());
assert.ok(!preWeekHtml.includes('-2주차') && !preWeekHtml.includes('0주차'));
console.log('PASS: seven date-only links, weekly dividers, curated daily content, home exclusion');
