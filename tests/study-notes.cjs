const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context={window:{},AbortController,setTimeout,clearTimeout};
vm.runInNewContext(fs.readFileSync('js/study-store.js','utf8'),context);

const create=context.window.CodeWikiStudyStore.create;
const memory=new Map(),storage={getItem:k=>memory.get(k),setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
const note={id:'11111111-1111-4111-8111-111111111111',title:'Title',body:'',revision:0};
const tick=()=>new Promise(resolve=>setImmediate(resolve));
(async()=>{
 const requests=[];
 let store=create({rpc:(name,args)=>new Promise(resolve=>requests.push({name,args,resolve})),storage,owner:'admin',token:'session'});
 store.select(note);store.edit('Title','first');
 const saving=store.save();store.save();assert.equal(requests.length,1,'serialize duplicate saves');
 store.edit('Title','typed while saving');
 assert.equal(store.busy,true,'saving state is visible immediately');
 requests[0].resolve({data:{title:'Title',revision:1,updated_at:'2026-11-18T00:00:00Z'}});await saving;
 assert.equal(requests.length,1,'typing during a save never starts another server write');
 assert.equal(store.dirty,true);assert.equal(store.current.body,'typed while saving');
 const saveLatest=store.save();
 assert.equal(requests.length,2);assert.equal(requests[1].args.p_revision,1);assert.equal(requests[1].args.p_body,'typed while saving');
 requests[1].resolve({data:{title:'Title',revision:2}});await saveLatest;
 assert.equal(store.dirty,false);assert.equal(memory.size,0);
 assert.equal(store.current.updated_at,'2026-11-18T00:00:00Z','missing timestamp never erases the last confirmed save');
 store.edit(store.current.title,store.current.body);
 assert.equal(store.dirty,false,'unchanged content must not trigger another save');
 const savedRequests=requests.length;
 assert.equal(await store.save(),true);assert.equal(requests.length,savedRequests,'clean save does not issue a write');
 store.edit('Draft','unsaved');const fail=store.save();requests[2].resolve({error:{message:'offline'}});assert.equal(await fail,false);
 assert.equal(store.current.body,'unsaved');assert.equal(store.dirty,true);
 store.dispose();
 store=create({rpc:async()=>({error:{code:'PT409'}}),storage,owner:'admin',token:'new-session'});
 assert.equal(store.current.body,'unsaved','restore private draft after reopening');
 assert.equal(await store.save(),false);assert.match(store.status,/다른 버전/);assert.equal(store.current.body,'unsaved');
 const other=create({rpc:async()=>({}),storage,owner:'other',token:'other-session'});
 assert.equal(other.current,null,'another account never sees the draft');
 let finish;const old=create({rpc:()=>new Promise(r=>finish=r),storage,owner:'old',token:'old'});
 old.select(note);old.edit('Old','draft');const pending=old.save();old.dispose();finish({data:{title:'Saved',revision:1}});await pending;
 assert.equal(old.current.revision,0,'late save cannot revive disposed session');
 const noCache=create({rpc:async()=>({data:{title:'Saved',revision:1}}),storage:{getItem(){return null;},setItem(){throw Error();},removeItem(){throw Error();}},owner:'private',token:'x'});
 noCache.select(note);noCache.edit('Saved','text');assert.match(noCache.status,/임시 저장/);assert.equal(await noCache.save(),true,'server saves work when browser cache is unavailable');
 let lateResolve,attempt=0;
 const timeoutStore=create({rpc:(name,args)=>{
   if(name==='cw_get_study_note')return Promise.resolve({data:{...note,title:'Timed',body:'retained',revision:1,updated_at:'2026-11-18T09:00:00Z'}});
   if(attempt++===0)return new Promise(resolve=>lateResolve=resolve);
   return Promise.resolve({error:{code:'PT409'}});
 },storage,owner:'timeout',token:'x',requestTimeout:5});
 timeoutStore.select(note);timeoutStore.edit('Timed','retained');
 assert.equal(await timeoutStore.save(),false);
 assert.equal(timeoutStore.busy,false);assert.equal(timeoutStore.dirty,true);
 assert.match(timeoutStore.status,/지연/);assert.ok(memory.has('codewiki_study_draft_v1:timeout'));
 lateResolve({data:{title:'late result',revision:99,updated_at:'2026-11-18T10:00:00Z'}});await tick();
 assert.equal(timeoutStore.current.revision,0,'late timed-out response cannot modify a draft');
 assert.equal(await timeoutStore.save(),true,'retry reconciles an identical server commit');
 assert.equal(timeoutStore.current.revision,1);assert.equal(timeoutStore.current.updated_at,'2026-11-18T09:00:00Z');
 assert.equal(timeoutStore.dirty,false);
 const mismatch=create({rpc:async name=>name==='cw_get_study_note'?{data:{...note,title:'Other',body:'different',revision:3}}:{error:{code:'PT409'}},storage,owner:'mismatch',token:'x'});
 mismatch.select(note);mismatch.edit('Keep','mine');assert.equal(await mismatch.save(),false);
 assert.equal(mismatch.current.body,'mine');assert.equal(mismatch.dirty,true);
 for(const code of ['PT409','40001']) {
   const calls=[];
   const conflict=create({rpc:async name=>{calls.push(name);return name==='cw_get_study_note'?{data:null}:{error:{code}};},storage,owner:'conflict-'+code,token:'x'});
   conflict.select(note);conflict.edit('Keep','private draft');
   assert.equal(await conflict.save(),false);await tick();
   assert.deepEqual(calls,['cw_save_study_note','cw_get_study_note'],'conflicts never automatically retry the write');
   assert.match(conflict.status,/다른 버전/);assert.equal(conflict.busy,false);
   assert.equal(conflict.dirty,true);assert.equal(conflict.current.body,'private draft');
   conflict.edit('Keep','new private draft');await conflict.save();
   assert.equal(calls.length,2,'editing or retrying a known conflict must not send more requests');
   const restored=create({rpc:async()=>{throw Error('must not request');},storage,owner:'conflict-'+code,token:'x'});
   assert.equal(restored.conflicted,true);assert.equal(await restored.save(),false);
 }
 let server={...note,title:'Server title',body:'Server text',revision:8},resolves=0;
 const resolveStore=create({rpc:async(name,args)=>{
   if(name==='cw_get_study_note')return {data:{...server}};
   resolves++;
   if(args.p_revision!==server.revision)return {error:{code:'PT409'}};
   server={...server,title:args.p_title,body:args.p_body,revision:server.revision+1,updated_at:'2026-11-18T10:00:00Z'};
   return {data:{...server}};
 },storage,owner:'resolve',token:'x'});
 resolveStore.select({...note,revision:2});resolveStore.edit('My title','My text');
 assert.equal(await resolveStore.save(),false);assert.equal(server.body,'Server text');
 assert.equal(resolveStore.conflicted,true);
 assert.equal(await resolveStore.save({resolveConflict:true}),true);
 assert.equal(resolves,2);assert.equal(server.body,'My text');assert.equal(server.revision,9);
 assert.equal(resolveStore.conflicted,false);assert.equal(resolveStore.dirty,false);
 assert.equal(resolveStore.current.updated_at,'2026-11-18T10:00:00Z');
 let raceWrites=0;
 const race=create({rpc:async name=>name==='cw_get_study_note'?{data:{...note,body:'server text',revision:10}}:(raceWrites++,{error:{code:'PT409'}}),storage,owner:'conflict-race',token:'x'});
 race.select({...note,revision:2});race.edit('Local','keep local');
 assert.equal(await race.save(),false);
 assert.equal(await race.save({resolveConflict:true}),false);
 assert.equal(raceWrites,2,'a concurrent edit during resolution stops after one write, without retry loops');
 assert.equal(race.conflicted,true);assert.equal(race.current.body,'keep local');assert.equal(race.dirty,true);
 const invalid=create({rpc:async()=>({data:null}),storage,owner:'invalid',token:'x'});
 invalid.select(note);invalid.edit('Local','keep');assert.equal(await invalid.save(),false);
 assert.equal(invalid.dirty,true);assert.match(invalid.status,/저장 결과/);
 const schema=fs.readFileSync('migrations/20261118-study-notes.sql','utf8');
 assert.doesNotMatch(schema,/errcode\s*=\s*'40001'/i,'business conflicts must not trigger PostgREST transaction retries');
 assert.equal((schema.match(/errcode='PT409'/g)||[]).length,2,'save and delete both return HTTP 409');
 console.log('PASS: bounded manual saves, explicit conflict resolution, timeout readback, last-save timestamp, draft retention and stale sessions');
})().catch(error=>{console.error(error);process.exitCode=1;});
